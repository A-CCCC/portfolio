// scripts/photo-manifest.mjs
//
// Lists what is in each public/photos/<page>/ folder so the pages can show
// photos without anyone maintaining a list in the code. A browser cannot read a
// directory, and Vite can only scan files under src/, so the folders are read
// here at build time and written out as a small module the pages import.
//
// Runs automatically from vite.config.js — on every build and when the dev
// server starts.
import { readdirSync, writeFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const PHOTO_ROOT = 'public/photos'
const OUT = 'src/data/pagePhotos.js'
const IMAGE = /\.(jpe?g|png|webp|avif)$/i

// A subfolder of a page's folder is a stage of the work — "02-frame" — and
// holds that stage's photos and, optionally, a note.txt with a line or two
// about it. Named after the folder, minus its number: "Frame".
const stageTitle = (folder) => {
  const words = folder.replace(/^\d+[-_ ]*/, '').replace(/[-_]+/g, ' ').trim()
  return words.charAt(0).toUpperCase() + words.slice(1)
}

export function buildPhotoManifest() {
  const pages = {}
  const stages = {}

  for (const page of readdirSync(PHOTO_ROOT, { withFileTypes: true })) {
    if (!page.isDirectory()) continue
    const dir = join(PHOTO_ROOT, page.name)
    const files = readdirSync(dir)
      .filter((f) => IMAGE.test(f))
      .sort()                                   // filename order, so a numeric prefix sets it
      .map((f) => `/photos/${page.name}/${f}`)
    if (files.length) pages[page.name] = files

    const found = []
    for (const sub of readdirSync(dir, { withFileTypes: true })) {
      if (!sub.isDirectory()) continue
      const inside = join(dir, sub.name)
      const photos = readdirSync(inside)
        .filter((f) => IMAGE.test(f))
        .sort()
        .map((f) => `/photos/${page.name}/${sub.name}/${f}`)
      const notePath = join(inside, 'note.txt')
      const note = existsSync(notePath) ? readFileSync(notePath, 'utf8').trim() : ''
      // A stage with neither photos nor a note is a folder waiting to be
      // filled, and shows nothing.
      if (photos.length || note) found.push({ slug: sub.name, title: stageTitle(sub.name), photos, note })
    }
    if (found.length) stages[page.name] = found.sort((a, b) => a.slug.localeCompare(b.slug))
  }

  const body = `// Generated by scripts/photo-manifest.mjs — do not edit.
// Add or remove files in public/photos/<page>/ and this is rewritten on the next
// build or dev-server start.
export default ${JSON.stringify(pages, null, 2)}

// The stages of the work, one per subfolder — see public/photos/PAGE-PHOTOS.md.
export const stages = ${JSON.stringify(stages, null, 2)}
`
  mkdirSync('src/data', { recursive: true })
  // only write when something changed, so the dev server does not reload itself
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== body) {
    writeFileSync(OUT, body)
  }
  return pages
}

// allow running it directly: `node scripts/photo-manifest.mjs`
if (import.meta.url === `file://${process.argv[1]}`) {
  const pages = buildPhotoManifest()
  for (const [page, files] of Object.entries(pages)) {
    console.log(`  ${page}: ${files.length} photo(s)`)
  }
  const { stages } = { stages: undefined }
  for (const page of readdirSync(PHOTO_ROOT, { withFileTypes: true })) {
    if (!page.isDirectory()) continue
    const subs = readdirSync(join(PHOTO_ROOT, page.name), { withFileTypes: true }).filter((d) => d.isDirectory())
    if (subs.length) console.log(`  ${page.name}: ${subs.length} stage folder(s)`)
  }
}
