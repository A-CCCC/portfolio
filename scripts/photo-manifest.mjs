// scripts/photo-manifest.mjs
//
// Lists what is in each public/photos/<page>/ folder so the pages can show
// photos without anyone maintaining a list in the code. A browser cannot read a
// directory, and Vite can only scan files under src/, so the folders are read
// here at build time and written out as a small module the pages import.
//
// Runs automatically from vite.config.js — on every build and when the dev
// server starts.
import { readdirSync, writeFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const PHOTO_ROOT = 'public/photos'
const OUT = 'src/data/pagePhotos.js'
const IMAGE = /\.(jpe?g|png|webp|avif)$/i

export function buildPhotoManifest() {
  const pages = {}

  for (const page of readdirSync(PHOTO_ROOT, { withFileTypes: true })) {
    if (!page.isDirectory()) continue
    const files = readdirSync(join(PHOTO_ROOT, page.name))
      .filter((f) => IMAGE.test(f))
      .sort()                                   // filename order, so a numeric prefix sets it
      .map((f) => `/photos/${page.name}/${f}`)
    if (files.length) pages[page.name] = files
  }

  const body = `// Generated by scripts/photo-manifest.mjs — do not edit.
// Add or remove files in public/photos/<page>/ and this is rewritten on the next
// build or dev-server start.
export default ${JSON.stringify(pages, null, 2)}
`
  mkdirSync('src/data', { recursive: true })
  // only write when something changed, so the dev server does not reload itself
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== body) {
    writeFileSync(OUT, body)
  }
  return pages
}

// allow running it directly: `node scripts/photo-manifest.mjs`
if (import.meta.url === `file://${process.argv[1]}`) {
  const pages = buildPhotoManifest()
  for (const [page, files] of Object.entries(pages)) {
    console.log(`  ${page}: ${files.length} photo(s)`)
  }
}
